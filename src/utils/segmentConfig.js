export function getSegmentPresetList() {
  return Object.values(SEGMENT_PRESETS);
}

export function getSegmentLabels(source) {
  const segmentId =
    source?.segmento && SEGMENT_PRESETS[source.segmento] ? source.segmento : 'geral';
  const preset = SEGMENT_PRESETS[segmentId] || SEGMENT_PRESETS.geral;
  const custom =
    source?.segmento_config && typeof source.segmento_config === 'object'
      ? source.segmento_config
      : {};

  const usesItems =
    typeof custom.usesItems === 'boolean' ? custom.usesItems : preset.usesItems;

  return {
    ...preset,
    customerSingular: custom.customerSingular || preset.customerSingular,
    customerPlural: custom.customerPlural || preset.customerPlural,
    itemSingular: custom.itemSingular || preset.itemSingular,
    itemPlural: custom.itemPlural || preset.itemPlural,
    itemCodeLabel: custom.itemCodeLabel || preset.itemCodeLabel,
    itemNameLabel: custom.itemNameLabel || preset.itemNameLabel,
    usesItems,
  };
}
